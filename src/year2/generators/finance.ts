/**
 * Year 2 Scenario Generator — Finance Generator
 *
 * Generates finance stories: journal entries, budgets, billing invoices,
 * expenses, and month-end close entries.
 */

import type { ApiStory } from "../api-stories";
import type { GeneratorContext } from "../types";
import { step, generatedAssertions } from "../types";
import { randomDateTimeInMonth, nextJournalCode, nextExpenseCode, nextInvoiceCode } from "../probability";
import { selectActor, isQuarterlyMonth } from "../business-rules";

// ─── Journal Entries ──────────────────────────────────────────────────────────

function generateJournalStories(ctx: GeneratorContext): ApiStory[] {
  const { rng, month, state } = ctx;
  const stories: ApiStory[] = [];
  const actor = selectActor("finance", state.employees, rng);
  const count = rng.int(3, 8);

  const entryTypes = [
    { account: "REVENUE-SERVICES", costCenter: "CC-DELIVERY", desc: "Service revenue recognition", debitRange: [100000, 2000000] as [number, number] },
    { account: "SALARY-EXPENSE", costCenter: "CC-ENG", desc: "Monthly salary expense", debitRange: [200000, 800000] as [number, number] },
    { account: "RENT-EXPENSE", costCenter: "CORPORATE", desc: "Office rent payment", debitRange: [50000, 200000] as [number, number] },
    { account: "CLOUD-INFRA-EXPENSE", costCenter: "CC-ENG", desc: "Cloud infrastructure cost", debitRange: [30000, 150000] as [number, number] },
    { account: "SOFTWARE-LICENSE", costCenter: "CORPORATE", desc: "Software license renewal", debitRange: [20000, 100000] as [number, number] },
    { account: "TRAVEL-EXPENSE", costCenter: "CC-DELIVERY", desc: "Client site travel expense", debitRange: [10000, 80000] as [number, number] },
    { account: "PROFESSIONAL-FEES", costCenter: "CORPORATE", desc: "Legal and consulting fees", debitRange: [25000, 150000] as [number, number] },
    { account: "MARKETING-EXPENSE", costCenter: "CC-SALES", desc: "Marketing campaign spend", debitRange: [20000, 120000] as [number, number] },
    { account: "INSURANCE-PREMIUM", costCenter: "CORPORATE", desc: "Insurance premium payment", debitRange: [15000, 60000] as [number, number] },
    { account: "EQUIPMENT-EXPENSE", costCenter: "CC-ENG", desc: "IT equipment purchase", debitRange: [30000, 200000] as [number, number] },
  ];

  for (let i = 0; i < count; i++) {
    ctx.sequence++;
    const entryType = rng.pick(entryTypes);
    const jeCode = nextJournalCode();
    const day = Math.max(1, Math.min(28, Math.floor((i / count) * 25) + 1));

    stories.push({
      id: `Y2-${month}-${String(ctx.sequence).padStart(3, "0")}`,
      month: month as ApiStory["month"],
      companyTime: randomDateTimeInMonth(rng, month, day, day + 2),
      actorId: actor.actorId,
      actorRole: actor.actorRole,
      module: "finance",
      preconditions: ["Finance books are open", `${month} period active`],
      intent: `Journal entry: ${entryType.desc} (${jeCode}).`,
      steps: [
        step("finance", "POST", "/api/journal-entries", 201, {
          entryNo: jeCode,
          entryDate: `${month}-${String(day).padStart(2, "0")}`,
          fiscalPeriod: `${month.slice(0, 4)}-Q${Math.ceil(Number(month.slice(5, 7)) / 3)}`,
          accountCode: entryType.account,
          costCenter: entryType.costCenter,
          description: `${entryType.desc} for ${month}. Auto-generated by Year 2 simulation.`,
          debit: rng.int(entryType.debitRange[0], entryType.debitRange[1]),
          preparedBy: actor.actorEmail,
          status: "posted",
        }, "/api/journal-entries?pageSize=200"),
      ],
      expectedState: [`Journal entry ${jeCode} posted`],
      crossEvents: ["finance.journal-posted"],
      notifications: [],
      edgeCases: [],
      assertions: generatedAssertions,
    });
  }

  return stories;
}

// ─── Expenses ─────────────────────────────────────────────────────────────────

function generateExpenseStories(ctx: GeneratorContext): ApiStory[] {
  const { rng, month, state } = ctx;
  const stories: ApiStory[] = [];
  const count = rng.int(2, 6);

  const expenseCategories = [
    { category: "travel", desc: "Client site visit travel", amountRange: [5000, 50000] as [number, number] },
    { category: "meals", desc: "Team lunch / client meeting", amountRange: [500, 5000] as [number, number] },
    { category: "hardware", desc: "Laptop accessories / peripherals", amountRange: [2000, 25000] as [number, number] },
    { category: "software", desc: "Software subscription", amountRange: [1000, 15000] as [number, number] },
    { category: "lodging", desc: "Hotel stay for client engagement", amountRange: [3000, 30000] as [number, number] },
    { category: "other", desc: "Phone / internet reimbursement", amountRange: [500, 3000] as [number, number] },
  ];

  for (let i = 0; i < count; i++) {
    ctx.sequence++;
    const emp = rng.pick(state.employees);
    const cat = rng.pick(expenseCategories);
    const expCode = nextExpenseCode();
    const amount = rng.int(cat.amountRange[0], cat.amountRange[1]);

    stories.push({
      id: `Y2-${month}-${String(ctx.sequence).padStart(3, "0")}`,
      month: month as ApiStory["month"],
      companyTime: randomDateTimeInMonth(rng, month, 3 + i * 3, 5 + i * 3),
      actorId: emp.employeeCode,
      actorRole: "member",
      module: "expense",
      preconditions: [`${emp.fullName} is an active employee`],
      intent: `${emp.fullName} submits expense: ${cat.desc} (${Math.round(amount / 1000)}K).`,
      steps: [
        step("expense", "POST", "/api/claims", 201, {
          claimNo: expCode,
          employeeCode: emp.employeeCode,
          employeeEmail: emp.email,
          category: cat.category,
          amount,
          expenseDate: randomDateTimeInMonth(rng, month, 1 + i * 3, 3 + i * 3).slice(0, 10),
          status: "draft",
        }, "/api/claims?pageSize=200"),
      ],
      expectedState: [`Expense ${expCode} approved for ${emp.fullName}`],
      crossEvents: ["expense.approved"],
      notifications: ["Finance notified for reimbursement"],
      edgeCases: [],
      assertions: generatedAssertions,
    });
  }

  return stories;
}

// ─── Billing Invoices ─────────────────────────────────────────────────────────

function generateBillingStories(ctx: GeneratorContext): ApiStory[] {
  const { rng, month, state } = ctx;
  const stories: ApiStory[] = [];

  // 1-3 invoices per month based on active projects.
  const invoiceCount = rng.int(1, Math.min(3, Math.max(1, state.activeProjectCount)));
  const actor = selectActor("finance", state.employees, rng);

  for (let i = 0; i < invoiceCount; i++) {
    ctx.sequence++;
    const customer = state.customers.length > 0
      ? rng.pick(state.customers).name
      : "Default Customer";
    const amount = rng.int(100000, 2000000);

    // 2-step story: create invoice, then record payment linked to it
    stories.push({
      id: `Y2-${month}-${String(ctx.sequence).padStart(3, "0")}`,
      month: month as ApiStory["month"],
      companyTime: randomDateTimeInMonth(rng, month, 10 + i * 5, 15 + i * 5),
      actorId: actor.actorId,
      actorRole: actor.actorRole,
      module: "billing",
      preconditions: [`Customer ${customer} has active contract`],
      intent: `Generate invoice for ${customer} (${Math.round(amount / 100000)}L) and record payment.`,
      steps: [
        step("billing", "POST", "/api/invoices", 201, {
          invoiceNo: nextInvoiceCode(),
          billingAccount: `BA-${customer.slice(0, 3).toUpperCase()}-${String(ctx.sequence).padStart(3, "0")}`,
          customer,
          amount,
          currency: "inr",
          issueDate: `${month}-${String(rng.int(10, 20)).padStart(2, "0")}`,
          dueDate: randomDateTimeInMonth(rng, month, 25, 28).slice(0, 10),
          status: "draft",
          description: `Professional services for ${month}. Milestone-based billing.`,
        }, "/api/invoices?pageSize=200"),
        step("billing", "POST", "/api/receipts", 201, {
          customerId: "$PREV.createdId",
          amount: Math.round(amount * (rng.chance(0.7) ? 1 : rng.int(50, 99) / 100)),
          currency: "INR",
          receivedDate: randomDateTimeInMonth(rng, month, 20, 28).slice(0, 10),
          externalReference: `REC-Y2-${String(ctx.sequence).padStart(3, "0")}`,
          method: rng.pick(["bank_transfer", "upi", "cheque"]),
        }, "/api/receipts?pageSize=200"),
      ],
      expectedState: [`Invoice generated for ${customer}`, `Payment recorded against invoice`],
      crossEvents: ["billing.invoice-generated", "billing.payment-recorded"],
      notifications: ["Invoice sent to customer", "Finance team notified of payment"],
      edgeCases: [],
      assertions: generatedAssertions,
    });
  }

  return stories;
}

// ─── Budget Entries (quarterly) ───────────────────────────────────────────────

function generateBudgetStories(ctx: GeneratorContext): ApiStory[] {
  const { rng, month, state } = ctx;
  const stories: ApiStory[] = [];

  if (!isQuarterlyMonth(month)) return stories;

  ctx.sequence++;
  const actor = selectActor("finance", state.employees, rng);
  const quarterBudget = rng.int(2000000, 10000000);

  stories.push({
    id: `Y2-${month}-${String(ctx.sequence).padStart(3, "0")}`,
    month: month as ApiStory["month"],
    companyTime: randomDateTimeInMonth(rng, month, 1, 3),
    actorId: actor.actorId,
    actorRole: actor.actorRole,
    module: "finance",
    preconditions: ["Quarterly budget planning cycle"],
    intent: `Set quarterly department budget.`,
    steps: [
      step("finance", "POST", "/api/budgets", 201, {
        name: `Department Budget ${month}`,
        amount: quarterBudget,
        currency: "INR",
        period: `${month.slice(0, 4)}-Q${Math.ceil(Number(month.slice(5, 7)) / 3)}`,
        costCenter: rng.pick(["CC-ENG", "CC-SALES", "CC-DELIVERY", "CORPORATE"]),
        status: "approved",
        description: `Quarterly budget allocation for ${month}. Approved by Finance Controller.`,
      }, "/api/budgets?pageSize=200"),
    ],
    expectedState: ["Quarterly budget set and approved"],
    crossEvents: ["finance.budget-set"],
    notifications: ["Department heads notified of budget allocation"],
    edgeCases: [],
    assertions: generatedAssertions,
  });

  return stories;
}

// ─── Combined Finance Generator ───────────────────────────────────────────────

export function generateFinanceStories(ctx: GeneratorContext): ApiStory[] {
  return [
    ...generateJournalStories(ctx),
    ...generateExpenseStories(ctx),
    ...generateBillingStories(ctx),
    ...generateBudgetStories(ctx),
  ];
}
