//    → Attendance → Payroll → Resource Allocation → Project → Billing
//    Correlation IDs: CHAIN-HIRE-001..N (one per hire)
//
// 2. REVENUE chain (chain: "revenue")
//    CRM Lead → Opportunity → Presales Request → Proposal → Contract
//    → Project → Milestone Acceptance → Invoice → Receipt → GL Journal
//    Correlation IDs: CHAIN-REV-001..N (one per deal)
//
// 3. DELIVERY chain (chain: "delivery")
//    SDLC Requirement → Epic → Sprint → Build → QA Test → Defect
//    → DevOps Deploy → Release Gate → Production
//    Correlation IDs: CHAIN-DELIVER-001..N (one per release cycle)
//
// 4. OPERATIONS chain (chain: "operations")
//    Procurement PR → RFQ → PO → Inventory GRN → Stock Receipt
//    → Asset Assignment → Lifecycle
//    Correlation IDs: CHAIN-OPS-001..N (one per procurement cycle)
//
// 5. GOVERNANCE chain (chain: "governance")
//    Security Finding → Risk Assessment → Control → Compliance Evidence
//    → Audit Finding → Remediation → Verification
//    Correlation IDs: CHAIN-GOV-001..N (one per governance cycle)
//
// Entity references (`entities` field) track the specific IDs created at each
// step, enabling the simulation to verify that e.g. the requisition created
// in Recruitment is linked to the position created in Organization, and the
// employee created in HR is linked to the candidate from Recruitment.

